"""RQ3 Evaluation: Static Boundary Hints in Uncovered Code (Task J7).

Evaluates static boundary hints against runtime coverage of DuckDB:
1. Computes coverage rates across hint kinds (branch, magic_const, sink).
2. Computes coverage rates across DuckDB subsystems (execution, function, optimizer, planner, storage).
3. Exports machine-readable raw data to paper/data/ and LaTeX table to paper/tables/.

Usage:
    python src/static/eval_hints.py [--data-dir=paper/data] [--tables-dir=paper/tables]
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from pathlib import Path

CODE = Path(__file__).resolve().parent.parent
WORK = Path(os.environ.get("FUZZ_WORK", Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(CODE / "coverage"))
from cov import Coverage  # noqa: E402

DEFAULT_DATA_DIR = CODE.parent / "paper" / "data"
DEFAULT_TABLES_DIR = CODE.parent / "paper" / "tables"


def format_latex_table(hc: dict) -> str:
    """Generate LaTeX booktabs table conforming strictly to paper/STYLE.md."""
    lines = [
        "%% Auto-generated by src/static/eval_hints.py for RQ3",
        "\\begin{table}[t]",
        "  \\caption{Static boundary hints and their coverage under the seed corpus. "
        "\\emph{Total}: hints extracted via AST analysis. "
        "\\emph{Inst.}: hints on instrumented lines. "
        "\\emph{Hit}: hints executed at least once. "
        "\\emph{Uncov.}: unexecuted hints forming the target set for directed generation. "
        "\\emph{Hit\\%}: fraction of instrumented hints executed.}",
        "  \\label{tab:rq3_hints}",
        "  \\footnotesize",
        "  \\centering",
        "  \\begin{tabular}{lrrrrr}",
        "    \\toprule",
        "    Subsystem & Total & Inst. & Hit & Uncov. & Hit\\% \\\\",
        "    \\midrule",
    ]

    # Subsystem breakdown
    for sub, st in sorted(hc.get("by_subsystem", {}).items()):
        short_sub = sub.replace("src/", "")
        inst = st["hit"] + st["miss"]
        lines.append(
            f"    {short_sub:<12s} & {st['total']:5,d} & {inst:5,d} & {st['hit']:5,d} & {st['miss']:5,d} & {st['hit_pct']:5.1f}\\% \\\\"
            .replace(",", "{,}")
        )

    lines.extend([
        "    \\midrule",
        "    \\multicolumn{6}{l}{\\textit{Breakdown by Hint Category}} \\\\",
        "    \\midrule",
    ])

    for kind, st in sorted(hc.get("by_kind", {}).items()):
        inst = st["hit"] + st["miss"]
        lines.append(
            f"    \\quad\\texttt{{{kind}}} & {st['total']:5,d} & {inst:5,d} & {st['hit']:5,d} & {st['miss']:5,d} & {st['hit_pct']:5.1f}\\% \\\\"
            .replace(",", "{,}")
        )

    # Total row
    tot = hc["total_hints"]
    inst_tot = hc["instrumented_hints"]
    hit_tot = hc["hit_hints"]
    miss_tot = hc["missed_hints"]
    pct_tot = hc["hit_rate_pct"]

    lines.extend([
        "    \\midrule",
        f"    Total & {tot:5,d} & {inst_tot:5,d} & {hit_tot:5,d} & {miss_tot:5,d} & {pct_tot:5.1f}\\% \\\\"
        .replace(",", "{,}"),
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
    ])
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir", default=str(DEFAULT_DATA_DIR), help="Output directory for raw data")
    ap.add_argument("--tables-dir", default=str(DEFAULT_TABLES_DIR), help="Output directory for LaTeX tables")
    ap.add_argument("--cov-dir", default=str(WORK / "results" / "cov"), help="Coverage data directory")
    a = ap.parse_args()

    data_dir = Path(a.data_dir)
    tables_dir = Path(a.tables_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    tables_dir.mkdir(parents=True, exist_ok=True)

    cov = Coverage(a.cov_dir)
    if not cov.profdata.exists():
        print(f"Error: {cov.profdata} not found. Run fuzzing first.", file=sys.stderr)
        sys.exit(1)

    print("Evaluating static hints coverage (RQ3)...")
    hc = cov.hints_coverage()

    # 1. Export summary JSON
    summary_path = data_dir / "rq3_hints_summary.json"
    summary_path.write_text(json.dumps(hc, indent=2))
    print(f"  Exported: {summary_path}")

    # 2. Export by_kind CSV
    kind_csv_path = data_dir / "rq3_hints_by_kind.csv"
    with open(kind_csv_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["kind", "total", "instrumented", "hit", "missed", "uninstrumented", "hit_pct"])
        for kind, st in sorted(hc.get("by_kind", {}).items()):
            inst = st["hit"] + st["miss"]
            w.writerow([kind, st["total"], inst, st["hit"], st["miss"], st["uninst"], st["hit_pct"]])
    print(f"  Exported: {kind_csv_path}")

    # 3. Export by_subsystem CSV
    sub_csv_path = data_dir / "rq3_hints_by_subsystem.csv"
    with open(sub_csv_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["subsystem", "total", "instrumented", "hit", "missed", "uninstrumented", "hit_pct"])
        for sub, st in sorted(hc.get("by_subsystem", {}).items()):
            inst = st["hit"] + st["miss"]
            w.writerow([sub, st["total"], inst, st["hit"], st["miss"], st["uninst"], st["hit_pct"]])
    print(f"  Exported: {sub_csv_path}")

    # 4. Export LaTeX table
    tex_path = tables_dir / "tab_rq3_hints.tex"
    tex_content = format_latex_table(hc)
    tex_path.write_text(tex_content)
    print(f"  Exported: {tex_path}")

    print("\nSummary:")
    print(f"  Total Hints:        {hc['total_hints']:,}")
    print(f"  Instrumented Hints: {hc['instrumented_hints']:,}")
    print(f"  Hit Hints:          {hc['hit_hints']:,} ({hc['hit_rate_pct']}%)")
    print(f"  Uncovered Hints:    {hc['missed_hints']:,} ({100.0 - hc['hit_rate_pct']:.2f}%)")


if __name__ == "__main__":
    main()
