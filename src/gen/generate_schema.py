SCHEMAS = {
    "primitives_extreme.sql": generate_primitives_extreme,
    "nested_structures.sql": generate_nested_structures,
    "vector_boundaries.sql": generate_vector_boundaries,
    "null_patterns.sql": generate_null_patterns,
    "relational_schemas.sql": generate_relational_schemas,
}


def write_all(out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    generated = {}
    for name, gen_fn in SCHEMAS.items():
        dest = out_dir / name
        content = gen_fn()
        dest.write_text(content.strip() + "\n")
        generated[name] = dest
    return generated


def validate_file(sql_file: Path, duckdb_binary: Path | None = None) -> bool:
    """Validate that the generated SQL file executes with zero errors in DuckDB."""
    sql_text = sql_file.read_text(errors="replace")

    # Prefer in-tree binary if compiled
    if duckdb_binary and duckdb_binary.exists():
        proc = subprocess.run(
            [str(duckdb_binary), ":memory:"],
            input=sql_text,
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            print(f"Validation failed for {sql_file.name} using {duckdb_binary}:", file=sys.stderr)
            print(proc.stderr, file=sys.stderr)
            return False
        return True

    # Fallback to python duckdb module
    try:
        import duckdb
        con = duckdb.connect()
        con.execute(sql_text)
        con.close()
        return True
    except Exception as e:
        print(f"Validation failed for {sql_file.name} using python duckdb: {e}", file=sys.stderr)
        return False


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", default=str(DEFAULT_OUT), help="Output directory for generated SQL files")
    ap.add_argument("--validate", action="store_true", help="Validate generated SQL files against DuckDB")
    ap.add_argument("--duckdb-bin", default=None, help="Path to DuckDB executable for validation")
    a = ap.parse_args()

    out_dir = Path(a.out_dir)
    print(f"Generating DuckDB schemas into: {out_dir}")
    files = write_all(out_dir)

    for name, path in files.items():
        size_kb = path.stat().st_size / 1024
        print(f"  - {name:24s} ({size_kb:5.1f} KB)")

    if a.validate:
        bin_path = Path(a.duckdb_bin) if a.duckdb_bin else (BIN_ASAN if BIN_ASAN.exists() else None)
        print(f"\nValidating SQL schemas (using {bin_path or 'duckdb python module'})...")
        all_ok = True
        for name, path in files.items():
            ok = validate_file(path, bin_path)
            status = "PASS" if ok else "FAIL"
            print(f"  [{status}] {name}")
            if not ok:
                all_ok = False
        if not all_ok:
            sys.exit(1)
        print("\nAll generated schemas validated successfully with zero errors!")


if __name__ == "__main__":
    main()
